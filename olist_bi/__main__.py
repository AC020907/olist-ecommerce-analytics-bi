"""Command-line entry point.

    python -m olist_bi build     # rebuild raw -> staging -> analytics -> reporting
    python -m olist_bi check     # run data-quality / reconciliation checks
    python -m olist_bi export    # write demo pre-aggregates to demo/data/
    python -m olist_bi all       # build + check + export
"""
from __future__ import annotations

import argparse
import logging
import sys
from pathlib import Path

from .config import REPO_ROOT, get_settings

REPORT_PATH = REPO_ROOT / "reports" / "data_quality_report.md"


def _check(database_url: str, report_path: Path | None) -> int:
    from .quality import format_report, run_checks

    results = run_checks(database_url)
    report = format_report(results)
    print(report)
    if report_path:
        report_path.parent.mkdir(parents=True, exist_ok=True)
        report_path.write_text(
            "# Data Quality Report\n\n"
            "Generated by `python -m olist_bi check` against the full Olist dataset.\n"
            "`WARN` rows are known, documented source-data characteristics "
            "(see docs/data_quality_notes.md); `FAIL` rows would break the build in CI.\n\n"
            + report + "\n",
            encoding="utf-8",
        )
    return 1 if any(r.status == "FAIL" for r in results) else 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="olist_bi", description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("command", choices=["build", "check", "export", "all"])
    parser.add_argument("--data-dir", type=Path, help="folder with the 9 Olist CSVs (default: data/raw or $OLIST_DATA_DIR)")
    parser.add_argument("--report", type=Path, default=None, help=f"write the check report as Markdown (e.g. {REPORT_PATH.relative_to(REPO_ROOT)})")
    args = parser.parse_args(argv)

    logging.basicConfig(level=logging.INFO, format="%(message)s")
    settings = get_settings()
    data_dir = args.data_dir or settings.data_dir

    if args.command in ("build", "all"):
        from .pipeline import build

        build(settings.database_url, data_dir)
    status = 0
    if args.command in ("check", "all"):
        status = _check(settings.database_url, args.report)
    if args.command in ("export", "all"):
        from .export_demo import export

        export(settings.database_url)
    return status


if __name__ == "__main__":
    sys.exit(main())
